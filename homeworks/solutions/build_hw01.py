answer_code("""degrees = np.arange(1, 16)
rmse_train, rmse_test = [], []
for d in degrees:
    A_train = np.vander(t_train, d + 1, increasing=True)
    x, *_ = np.linalg.lstsq(A_train, y_train, rcond=None)
    A_test = np.vander(t_test, d + 1, increasing=True)
    rmse_train.append(np.sqrt(np.mean((A_train @ x - y_train) ** 2)))
    rmse_test.append(np.sqrt(np.mean((A_test @ x - y_test) ** 2)))

plt.figure(figsize=(5.5, 3.5))
plt.semilogy(degrees, rmse_train, "o-", label="обучающая")
plt.semilogy(degrees, rmse_test, "s-", label="тестовая")
plt.axhline(0.1, color="gray", ls="--", lw=1, label="уровень шума 0.1")
plt.xlabel("степень полинома $d$"); plt.ylabel("RMSE"); plt.legend(); plt.grid(alpha=0.3)
plt.title("Ошибка подгонки vs степень")
plt.show()

best = degrees[int(np.argmin(rmse_test))]
print("минимум тестовой ошибки при d =", best, " RMSE_test = %.4f" % min(rmse_test))""")
answer_md(r"""**Ответ (а).** Ошибка на обучающей выборке **монотонно не возрастает** с ростом $d$: полином степени $d$ — частный случай полинома степени $d+1$ (с нулевым старшим коэффициентом), а МНК находит наилучший в классе, поэтому расширение класса не может ухудшить подгонку. Тестовая ошибка сначала быстро падает (при $d = 1, 2$ модель слишком проста для синуса), достигает минимума около $d \approx 3$–$7$ на уровне шума $\approx 0.1$, а затем растёт: полином высокой степени начинает описывать шум обучающей выборки, который на тестовой другой. Это **переобучение**. Наблюдение: у обучающей кривой при больших $d$ значения могут слегка скакать — это уже влияние обусловленности матрицы Вандермонда, а не математики МНК.""")

