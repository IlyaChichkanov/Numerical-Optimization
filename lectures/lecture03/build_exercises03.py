md(r"""## 13.6. Проекция на шар через множители

> $\min\tfrac12\lVert x-p\rVert^2$ при $\lVert x\rVert^2\le r^2$. Выразите $x$ через $p$ и $\mu$, разберите два случая, посчитайте для $p=(3,4)$, $r=1$.

**Решение.** $h(x)=r^2-\lVert x\rVert^2$, $\nabla h=-2x$ — смотрит к центру, внутрь шара. Баланс сил $\nabla f=\mu\nabla h$: $x-p=-2\mu x$, откуда $x=\dfrac{p}{1+2\mu}$ — проекция лежит на луче из центра к $p$, и множитель лишь «укорачивает» $p$.

*Случай 1: ограничение активно*, $\lVert x^\ast\rVert=r$: $\dfrac{\lVert p\rVert}{1+2\mu}=r\Rightarrow\mu=\dfrac12\Big(\dfrac{\lVert p\rVert}{r}-1\Big)$. Знак $\mu\ge0$ ровно тогда, когда $\lVert p\rVert\ge r$ — точка снаружи или на сфере; тогда $x^\ast=r\,p/\lVert p\rVert$ — та же формула, что в лекции 2, только теперь она *выведена* из баланса сил, а не угадана.

*Случай 2: неактивно*, $\mu=0$: $x^\ast=p$ — точка и так внутри ($\lVert p\rVert<r$). Комплементарная нежёсткость выбирает случай автоматически: при $\lVert p\rVert<r$ формула случая 1 дала бы $\mu<0$ — стенка «притягивала» бы, значит, она не при чём.

Числа: $p=(3,4)$, $\lVert p\rVert=5$, $r=1$: $\mu=\tfrac12(5-1)=2$, $x^\ast=p/5=(0.6,\,0.8)$.""")

code("""p, r = np.array([3.0, 4.0]), 1.0
res = minimize(lambda x: 0.5 * np.sum((x - p) ** 2), x0=[0.0, 0.0], constraints=[{"type": "ineq", "fun": lambda x: r**2 - x @ x}])
mu = 0.5 * (np.linalg.norm(p) / r - 1)
print("x* численно =", res.x.round(4), "  формула p/(1+2mu) =", (p / (1 + 2 * mu)).round(4), "  mu =", mu)
assert np.allclose(res.x, p / (1 + 2 * mu), atol=1e-5)
grad_f, grad_h = res.x - p, -2 * res.x
print("баланс сил grad f - mu grad h =", (grad_f - mu * grad_h).round(6))""")

