md(r"""## 13.9. Чувствительность: знак в «цене ограничения»

> $\min (x_1-1)^2+(x_2-1)^2$ при $x_1+x_2\le b$, $b<2$. Найдите $x^\ast(b)$, $\mu^\ast(b)$, $f^\ast(b)$ и проверьте $df^\ast/db=-\mu^\ast$.

**Решение.** Безусловный минимум $(1,1)$ нарушает ограничение при $b<2$ — оно активно. $h=b-x_1-x_2$, $\nabla h=(-1,-1)$. Баланс: $2(x_1-1)=-\mu$, $2(x_2-1)=-\mu$ $\Rightarrow$ $x_1=x_2$, и из активности $x^\ast=(b/2,\,b/2)$. Тогда $\mu^\ast=2(1-b/2)=2-b>0$ ✓. Значение $f^\ast(b)=2(1-b/2)^2=(2-b)^2/2$, производная $df^\ast/db=-(2-b)=-\mu^\ast$.

Знак минус — здравый смысл: увеличить $b$ значит *ослабить* ограничение (допустимое множество растёт), минимум может только уменьшиться — на $\mu^\ast$ за единицу $b$. В заводе из лекции контракт $x\ge b$ при росте $b$ *ужесточался*, и там $df^\ast/db=+\mu^\ast$. Само число $\mu^\ast$ — цена ограничения, а знак определяется тем, в какую сторону сдвиг: ослабление помогает, ужесточение вредит. При $b\ge2$ точка $(1,1)$ допустима, $\mu^\ast=0$, $f^\ast=0$ — цена ноль.""")

code("""for b in (0.5, 1.0, 1.5, 2.5):
    r = minimize(lambda x: (x[0] - 1) ** 2 + (x[1] - 1) ** 2, x0=[0, 0], constraints=[{"type": "ineq", "fun": lambda x, b=b: b - x[0] - x[1]}])
    mu = max(2 - b, 0.0)
    eps = 1e-5
    fstar = lambda bb: minimize(lambda x: (x[0] - 1) ** 2 + (x[1] - 1) ** 2, x0=[0, 0], constraints=[{"type": "ineq", "fun": lambda x: bb - x[0] - x[1]}]).fun
    dfdb = (fstar(b + eps) - fstar(b - eps)) / (2 * eps)
    print(f"b={b}: x*={r.x.round(3)}, f*={r.fun:.4f} (формула {max(2 - b, 0) ** 2 / 2:.4f}), mu*={mu:.2f}, df*/db={dfdb:.3f} = -mu*")""")

