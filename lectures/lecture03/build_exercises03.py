md(r"""## 13.10. Ящик наибольшего объёма

> $\max xyz$ при $2(xy+yz+zx)=S$, $x,y,z>0$. Покажите через $\nabla f=\lambda\nabla g$, что $x=y=z$; найдите сторону и $\lambda$.

**Решение.** $f=xyz$, $g=2(xy+yz+zx)-S$. Баланс сил (для максимума знак $\lambda$ всё равно свободен): $yz=2\lambda(y+z)$, $xz=2\lambda(x+z)$, $xy=2\lambda(x+y)$. Умножим первое на $x$, второе на $y$: $xyz=2\lambda x(y+z)=2\lambda y(x+z)$ $\Rightarrow$ $xz=yz$ $\Rightarrow$ $x=y$ (при $z>0$); аналогично $y=z$. Итак, куб: $6s^2=S$, $s=\sqrt{S/6}$; из первого уравнения $s^2=4\lambda s$, $\lambda=s/4$. Знак $\lambda$ здесь положителен, но это ничего не значит: у равенства он может быть любым, и если записать $g$ с обратным знаком, $\lambda$ сменит знак, а решение — нет. Что это максимум, а не минимум, из первого порядка не следует (при $x\to0$ объём стремится к нулю при той же площади — граница области); здесь помогает симметрия и здравый смысл, а в общем случае — условия второго порядка.""")

