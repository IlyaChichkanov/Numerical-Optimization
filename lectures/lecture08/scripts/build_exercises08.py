md(r"""## 8.0. Разминка — счёт руками

**(а) Ближайшая точка плоскости.** Функция Лагранжа:

$$
L=\tfrac12\lVert x-x_0\rVert^2-\lambda\,(q^\top x-d) .
$$

Из $\nabla_xL=x-x_0-\lambda q=0$ получаем $x=x_0+\lambda q$. Подставим в $q^\top x=d$: $q^\top x_0+\lambda\lVert q\rVert^2=d$. Отсюда

$$
\lambda=\frac{d-q^\top x_0}{\lVert q\rVert^2},\qquad x^\ast=x_0+\frac{d-q^\top x_0}{\lVert q\rVert^2}\,q .
$$

Это формула проекции на плоскость из лекции 2. Множитель — расстояние до плоскости со знаком, в единицах $\lVert q\rVert$. Второй порядок: $\nabla^2_{xx}L=I\succ0$, минимум.

**(б) $\min x_1+x_2$ на окружности.** $g=x_1^2+x_2^2-1$, $\nabla f=(1,1)=\lambda(2x_1,2x_2)$, значит $x_1=x_2=1/(2\lambda)$; из $g=0$: $2/(4\lambda^2)=1$, $\lambda=\pm1/\sqrt2$. Два решения: $x=(1,1)/\sqrt2$ с $\lambda=1/\sqrt2$ и $x=-(1,1)/\sqrt2$ с $\lambda=-1/\sqrt2$. Минимум — второе, $f=-\sqrt2$: там $\nabla^2_{xx}L=\nabla^2f-\lambda\nabla^2g=0+\tfrac{1}{\sqrt2}\cdot2I=\sqrt2\,I\succ0$; в первом $-\sqrt2\,I$ — максимум.

**(в) Ящик.** Стороны ящика — $x,y,z>0$. Объём $V=xyz$, площадь поверхности $2(xy+yz+zx)$. Задача:

$$
\max\ V=xyz\qquad\text{при}\qquad g=2(xy+yz+zx)-6=0 .
$$

Градиенты:

$$
\nabla V=(yz,\ xz,\ xy),\qquad\nabla g=2\,(y+z,\ x+z,\ x+y).
$$

**Система.** Условие касания $\nabla V=\lambda\nabla g$ — по одному уравнению на каждую сторону. Четвёртое уравнение — ограничение:

$$
\begin{aligned}
\text{по } x:&\quad yz=2\lambda(y+z),\\
\text{по } y:&\quad xz=2\lambda(x+z),\\
\text{по } z:&\quad xy=2\lambda(x+y),\\
\text{ограничение:}&\quad 2(xy+yz+zx)=6 .
\end{aligned}
$$

Четыре уравнения на четыре неизвестных: $x$, $y$, $z$ и $\lambda$.

**Шаг 1. $\lambda\ne0$.** Иначе первое уравнение даёт $yz=0$, а стороны положительны.

**Шаг 2. $x=y$.** Умножим первое уравнение на $x$, а второе — на $y$:

$$
xyz=2\lambda x(y+z),\qquad xyz=2\lambda y(x+z).
$$

Левые части одинаковы, значит, равны и правые. Разделим на $2\lambda\ne0$ и раскроем скобки:

$$
xy+xz=xy+yz\quad\Longrightarrow\quad xz=yz\quad\Longrightarrow\quad x=y .
$$

В последнем переходе делим на $z>0$.

**Шаг 3. $y=z$.** То же со вторым и третьим уравнением: умножим их на $y$ и на $z$. Получим $yx=zx$, то есть $y=z$.

Итак, $x=y=z$: ящик — куб. Это не догадка, а следствие системы. Обозначим сторону куба $s$.

**Шаг 4. Сторона и множитель.** Ограничение даёт $6s^2=6$, то есть $s=1$. Первое уравнение даёт $s^2=4\lambda s$, то есть $\lambda=s/4$:

$$
x=y=z=1,\qquad\lambda=\tfrac14 .
$$

**Знак.** Множитель — цена ограничения: $\lambda=dV^\ast/dS$ (семинар). При площади $S$ куб имеет сторону $\sqrt{S/6}$ и объём $V^\ast(S)=(S/6)^{3/2}$. Производная при $S=6$ равна $\tfrac32\cdot\tfrac16=\tfrac14$: лишняя единица площади даёт четверть единицы объёма. Знак плюс — объём растёт с площадью. В записи «минимизируем $-V$» множитель равен $-1/4$.""")

