md(r"""## 8.1. Две точки на окружности

**(а) Шаг 1. Система.** Градиенты $\nabla f=x-a$ и $\nabla g=x$. Условие касания $\nabla f=\lambda\nabla g$ даёт два уравнения, третье — само ограничение:

$$
x_1-2=\lambda x_1,\qquad x_2-1=\lambda x_2,\qquad x_1^2+x_2^2=1 .
$$

Три уравнения на три неизвестных: $x_1$, $x_2$ и $\lambda$.

**Шаг 2. Решение руками.** Первые два уравнения — это $x_1(1-\lambda)=2$ и $x_2(1-\lambda)=1$, то есть

$$
x=\frac{a}{1-\lambda}.
$$

Точка лежит на прямой через начало координат и $a$. Подставим её в ограничение:

$$
\frac{\lVert a\rVert^2}{(1-\lambda)^2}=1\quad\Longrightarrow\quad1-\lambda=\pm\lVert a\rVert=\pm\sqrt5 .
$$

Решений два:

- $\lambda=1-\sqrt5=-1.236$ и $x=a/\sqrt5=(0.894,\ 0.447)$ — ближняя точка;
- $\lambda=1+\sqrt5=3.236$ и $x=-a/\sqrt5=(-0.894,\ -0.447)$ — дальняя точка.

**Шаг 3. `fsolve`.** Функция `fsolve` из SciPy ищет нуль системы итерациями, начиная со старта. Старт справа приводит в ближнюю точку, старт слева — в дальнюю.

**Что делает ячейка.** Функция `circle_system` возвращает левые части трёх уравнений, перенесённые в одну сторону. Ячейка решает систему из двух стартов и печатает невязки.""")

code(r'''def circle_system(z, a):
    """Три уравнения 8.1 для точки a: две компоненты grad f = lambda grad g и ограничение."""
    x1, x2, lam = z                                                   # неизвестные: точка и множитель
    return [x1 - a[0] - lam * x1,                                     # первая компонента
            x2 - a[1] - lam * x2,                                     # вторая компонента
            x1**2 + x2**2 - 1]                                        # точка на окружности

a = np.array([2.0, 1.0])
for z0 in ([1, 0.5, 0], [-1, -0.5, 0]):                              # старты (x1, x2, lambda)
    z = fsolve(lambda z: circle_system(z, a), z0, xtol=1e-14)
    print(f"старт {z0}: x = ({z[0]:+.4f}, {z[1]:+.4f}), lambda = {z[2]:+.4f}, невязки {np.abs(circle_system(z, a)).max():.0e}")''')

md(r"""**Что видим.** Две точки и два множителя — как в шаге 2. Невязки — машинный ноль.

**(б) Шаг 4. Касательный вектор $Z$.** Ограничение одно, поэтому якобиан — одна строка: $J=\nabla g^\top=(x_1,\ x_2)$. Касательный вектор перпендикулярен радиусу:

$$
JZ=x_1Z_1+x_2Z_2=0\quad\Longrightarrow\quad Z=(-x_2,\ x_1).
$$

Это радиус, повёрнутый на $90^\circ$. Он единичный, потому что $x_1^2+x_2^2=1$. Функция `null_space(J)` возвращает тот же вектор, возможно со знаком минус.

**Шаг 5. Редуцированный гессиан.** Гессианы $\nabla^2f=I$ и $\nabla^2g=I$. Поэтому

$$
\nabla^2_{xx}L=\nabla^2f-\lambda\nabla^2g=(1-\lambda)\,I,\qquad Z^\top\nabla^2_{xx}L\,Z=(1-\lambda)\,Z^\top Z=1-\lambda .
$$

В ближней точке $1-\lambda=2.236>0$ — минимум. В дальней $1-\lambda=-2.236<0$ — максимум. Это расчёт §4.3 лекции.

**Шаг 6. Точка $a=(0.3,\ 0.1)$ внутри круга.** Шаги 2 и 5 не зависят от того, где лежит $a$. Теперь $\lVert a\rVert=0.316$, и

$$
\lambda=1\mp0.316,\qquad Z^\top\nabla^2_{xx}L\,Z=1-\lambda=\pm0.316 .
$$

Ближняя точка $a/\lVert a\rVert=(0.949,\ 0.316)$ по-прежнему минимум. Но её множитель $\lambda=0.684$ теперь положительный.

**Почему сменился знак.** Из первых двух уравнений $x-a=\lambda x$. В ближней точке вектор $x-a$ направлен от $a$ к окружности. Если $a$ снаружи, это направление к центру, против $x$, и $\lambda<0$. Если $a$ внутри, это направление от центра, вдоль $x$, и $\lambda>0$.

**Вывод.** Знак $\lambda$ зависит от того, где лежит $a$. Минимум от максимума отличает редуцированный гессиан.

**Что делает ячейка.** Для двух точек $a$ решает систему из двух стартов. В каждом решении строит $Z$ функцией `null_space` и считает $Z^\top\nabla^2_{xx}L\,Z$.""")

code(r'''def classify(a):
    """Оба решения системы и редуцированный гессиан в каждом."""
    rows = []
    for z0 in ([1, 0.5, 0], [-1, -0.5, 0]):
        z = fsolve(lambda z: circle_system(z, a), z0, xtol=1e-14)      # (x, lam) из старта z0
        x, lam = z[:2], z[2]
        Z = null_space(x.reshape(1, -1))                               # касательный вектор: J Z = 0, J = x^T
        H = (1 - lam) * np.eye(2)                                      # hess_xx L = hess f - lam hess g = (1 - lam) I
        red = (Z.T @ H @ Z).item()                                     # редуцированный гессиан — число
        rows.append((x, lam, red, "минимум" if red > 0 else "максимум"))
    return rows

for a in (np.array([2.0, 1.0]), np.array([0.3, 0.1])):
    print(f"a = {a}:")
    for x, lam, red, kind in classify(a):
        print(f"   x = ({x[0]:+.4f}, {x[1]:+.4f}), lambda = {lam:+.4f}, Z^T H Z = {red:+.4f} -> {kind}")''')

