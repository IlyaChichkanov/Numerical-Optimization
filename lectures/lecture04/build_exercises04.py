    formula = 2 - 2 * np.cos(np.arange(1, n + 1) * np.pi / (n + 1))
    print(f"{n:3d}  {ev[-1] / ev[0]:9.1f}  {(2 * (n + 1) / np.pi) ** 2:13.1f}   {np.abs(np.sort(formula) - ev).max():.1e}")

