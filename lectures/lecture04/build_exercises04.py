md(r"""## 12.10. Логистическая регрессия: выпуклость и масштаб признаков

> Логистическая регрессия (лекция 1, §7.5). Для $f(w)=\frac1n\sum_{i=1}^n\log\big(1+e^{-y_i\,x_i^\top w}\big)$, $y_i\in\{-1,1\}$, найдите $\nabla f$ и $\nabla^2f$ и докажите, что $f$ выпукла (гессиан имеет вид $\frac1n X^\top SX$ с диагональной $S\succeq0$). Объясните, почему признаки разного масштаба (возраст в годах и доход в рублях) дают большое $\kappa$ и как стандартизация признаков это лечит. Проверьте в демо (часть d).

**Решение.**

*Шаг 1. Градиент.* Обозначим $\sigma(t)=1/(1+e^{-t})$ и $\ell(t)=\log(1+e^{-t})$; тогда $f(w)=\frac1n\sum_i\ell(y_ix_i^\top w)$. Производная $\ell'(t)=\dfrac{-e^{-t}}{1+e^{-t}}=-\sigma(-t)$. По правилу цепочки
$$\nabla f(w)=\frac1n\sum_{i=1}^n\ell'(y_ix_i^\top w)\,y_ix_i=-\frac1n\sum_{i=1}^n\sigma(-y_ix_i^\top w)\,y_i\,x_i.$$
Смысл: $\sigma(-y_ix_i^\top w)$ — вероятность, которую модель приписывает **неправильному** классу; чем увереннее ошибка, тем сильнее объект тянет $w$.

*Шаг 2. Гессиан.* $\sigma'(t)=\sigma(t)(1-\sigma(t))$ и $\sigma(-t)=1-\sigma(t)$, поэтому $\frac d{dt}\big[-\sigma(-t)\big]=\sigma'(-t)=\sigma(t)(1-\sigma(t))$. Дифференцируя $\nabla f$ ещё раз по $w$ (внутри снова множитель $y_ix_i$, а $y_i^2=1$):
$$\nabla^2f(w)=\frac1n\sum_{i=1}^n\sigma(z_i)(1-\sigma(z_i))\,x_ix_i^\top=\frac1nX^\top SX,\qquad z_i=x_i^\top w,\quad S=\operatorname{diag}\big(\sigma(z_i)(1-\sigma(z_i))\big).$$
Заметим, что $y_i$ из гессиана исчез: кривизна зависит только от того, насколько уверенно модель классифицирует объект, а не от того, права ли она.

*Шаг 3. Выпуклость.* Диагональ $S$ неотрицательна ($\sigma\in(0,1)$), значит для любого $v$
$$v^\top\nabla^2f(w)\,v=\frac1n(Xv)^\top S(Xv)=\frac1n\sum_is_i(x_i^\top v)^2=\frac1n\|S^{1/2}Xv\|^2\ge0.$$
Гессиан $\succeq0$ всюду — $f$ выпукла. Строго выпукла, если столбцы $X$ линейно независимы (тогда $Xv\ne0$ при $v\ne0$, а $s_i>0$). Значит, любая стационарная точка — глобальный минимум, и градиентный спуск с Ньютоном находят его без оговорок.

*Шаг 4. Почему масштаб признаков даёт большое $\kappa$.* Гессиан — взвешенная матрица вторых моментов признаков: $\frac1nX^\top SX\approx\bar s\cdot\frac1nX^\top X$, если веса $s_i$ не слишком различаются. Диагональный элемент, отвечающий признаку $j$, равен $\frac1n\sum_is_ix_{ij}^2$ — порядка квадрата разброса признака. Если возраст измеряется десятками лет, а стаж — единицами, то диагональные элементы отличаются в $\sim100$ раз; доход в рублях (разброс $10^5$) против возраста (разброс $10$) даёт $10^8$. Собственные числа гессиана растягиваются в таком же соотношении, и $\kappa$ становится огромным — не потому, что задача трудна, а потому, что оси координат измерены разными линейками (ровно как в 12.5). Столбец единиц усугубляет дело: признак с большим средним сильно коррелирует с константой, и один из собственных векторов становится почти вырожденным.

*Шаг 5. Стандартизация.* Заменим $x_{ij}\leftarrow(x_{ij}-\mu_j)/\sigma_j$ для всех признаков, кроме константы. Тогда $\frac1nX^\top X$ имеет единицы на диагонали (корреляционная матрица), собственные числа — порядка единицы, $\kappa$ определяется только корреляциями признаков между собой. Это линейная замена $x\to A x+b$, то есть замена переменных $w\to A^{-\top}w$ — задача та же, а $\kappa$ другой: как и в 12.5, стандартизация — это диагональный предобусловливатель, выбранный по данным. В демо (часть d): без стандартизации $\kappa\approx7.5\cdot10^4$ и GD с backtracking не доходит до $\|\nabla f\|\le10^{-6}$ за 20 000 итераций; после стандартизации $\kappa\approx2.75$ и хватает 195 итераций. Ньютону масштаб безразличен — 6 итераций в обоих случаях.""")

