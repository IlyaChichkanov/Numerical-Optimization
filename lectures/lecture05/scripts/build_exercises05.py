md(r"""## 11.9. Цепь: квази-Ньютон на квадратичной (с кодом)

> (а) `bfgs` с точным шагом (`Q=H`) на цепи $N=10,20,40,80$: сколько итераций и почему не больше числа различных собственных чисел $H$. (б) То же с одним правилом Армихо: для каких $N$ сходится за $10\,000$ итераций, для каких нет; что сломалось.
>
> *Суть: BFGS с точным шагом конечен на квадратичной, а с одним лишь правилом Армихо хрупок.*

**(а)** $5,\ 10,\ 20,\ 40$ — ровно $N/2$. Теория (примем без доказательства): BFGS с точным линейным поиском на квадратичной функции сходится не более чем за число *различных* собственных чисел матрицы. У $H=\operatorname{diag}(DK,DK)$ собственные числа $D(2-2\cos\frac{j\pi}{N+1})$, $j=1..N$, каждое дважды — различных ровно $N$. Почему хватает $N/2$: старт (прямая между концами) и решение (парабола) симметричны относительно середины цепи, поэтому начальная ошибка раскладывается только по симметричным собственным векторам — их $N/2$.

**(б)** С одним правилом Армихо (шаг $\le1$) метод хрупок: при $N=10$ сходится за $42$ итерации, при $N=20$ и $N=40$ не сходится за $10\,000$, при $N=80$ снова сходится ($132$). Исход зависит от деталей округления, и это само по себе диагноз. Что ломается: в какой-то момент принятый шаг оказывается коротким, пара $(s,y)$ с крошечным $s$ почти не несёт информации о кривизне, но обновление всё равно меняет $H$; направление $p=-Hg$ становится слишком длинным, Армихо делит его десятки раз ($37$ вычислений $E$ на итерацию), принятые шаги падают до $10^{-9}$ — и метод стоит на месте, хотя $\lVert\nabla E\rVert$ уже близка к порогу. Лечение: точный шаг (на квадратичной он есть), условие кривизны Вольфе из §4.3 — оно не даёт принять шаг, после которого градиент вдоль направления почти не изменился, — или хотя бы масштабирование $H_0=\frac{s^\top y}{y^\top y}I$ после первого шага.""")

