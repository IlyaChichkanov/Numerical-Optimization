md(r"""**(д)** Левенберг–Марквардт по алгоритму §5.3: решаем $(J^\top J+\lambda I)p=-J^\top r$, считаем отношение выигрыша $\rho=(f-f_{\text{new}})/(L(0)-L(p))$ с $L(p)=\tfrac12\lVert r+Jp\rVert^2$, принимаем шаг при $\rho>0$, делим $\lambda$ на $3$ при $\rho>0.75$, удваиваем при $\rho<0.25$ и при отказе. Из старта ДЗ 2 №1 сравниваем с демпфированным Гауссом–Ньютоном: число итераций, отвергнутых шагов и куда пришли; `least_squares(method="lm")` — для контроля.""")

code(r"""def lm(resid, jac, x0, tol=1e-6, maxit=200):
    x = np.asarray(x0, float).copy(); r = resid(x); J = jac(x)
    lam = 1e-3 * np.max(np.diag(J.T @ J)); rejected = 0
    for k in range(maxit):
        g = J.T @ r
        if np.linalg.norm(g) <= tol:
            return x, k, rejected
        p = np.linalg.solve(J.T @ J + lam * np.eye(len(x)), -g)
        f_old, f_new = 0.5 * (r @ r), 0.5 * np.sum(resid(x + p) ** 2)
        pred = f_old - 0.5 * np.sum((r + J @ p) ** 2)            # L(0) - L(p), всегда >= 0
        rho = (f_old - f_new) / pred if pred > 0 else -1.0
        if rho > 0:
            x = x + p; r = resid(x); J = jac(x)
            if rho > 0.75: lam /= 3
            elif rho < 0.25: lam *= 2
        else:
            lam *= 2; rejected += 1
    return x, maxit, rejected

x_lm, k_lm, rej = lm(resid, jac, starts[0])
x_gnd, k_gnd, _ = gauss_newton(resid, jac, starts[0], damped=True, maxit=200)
r_lm = least_squares(resid, starts[0], jac=jac, method="lm")
print(f"(д) старт ДЗ 2 №1 = {starts[0].round(3)}")
print(f"    Левенберг–Марквардт:         {k_lm} итераций, отвергнуто шагов {rej}, x = {x_lm.round(4)}, f = {f_s(x_lm):.4f}")
print(f"    демпфированный Гаусс–Ньютон: {k_gnd} итераций,                     x = {x_gnd.round(4)}, f = {f_s(x_gnd):.4f}")
print(f"    scipy least_squares(lm):     {r_lm.nfev} вычислений невязки,         x = {r_lm.x.round(4)}, f = {r_lm.cost:.4f}")
print("    (глобальный минимум ДЗ 2: f* = 1.1393; другое значение f — локальный минимум с другой частотой)")""")

